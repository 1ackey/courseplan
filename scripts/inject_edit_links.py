#!/usr/bin/env python3
"""Append a call-to-action section to hand-written course pages.

Hand-written pages (courses without offerings in the DB) are not
regenerated by the export script, so this one-time content edit persists
in git. The section name is deliberately ignored by sync_from_files.
"""
import os
import re

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS_DIR = os.path.join(BASE_DIR, "docs", "categories")

MARKER = "提交这门课的开课记录"


def main():
    changed = 0
    for dir_name in sorted(os.listdir(DOCS_DIR)):
        dir_path = os.path.join(DOCS_DIR, dir_name)
        if not os.path.isdir(dir_path):
            continue
        for fname in sorted(os.listdir(dir_path)):
            if not re.match(r"^[A-Z]{2,4}\d{3}\.md$", fname):
                continue
            code = fname[:-3]
            path = os.path.join(dir_path, fname)
            with open(path, "r", encoding="utf-8") as f:
                text = f.read()
            if MARKER in text:
                continue
            if not text.endswith("\n"):
                text += "\n"
            text += (
                "\n## 参与编辑\n\n"
                "!!! note \"上过这门课？\"\n"
                f"    [提交这门课的开课记录](/notebook-admin/public/new/{code})，"
                "让下一届同学也能看到这门课的真实情况。\n"
            )
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            changed += 1
    print(f"inject_edit_links: {changed} pages updated")


if __name__ == "__main__":
    main()
